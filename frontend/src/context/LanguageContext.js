const normalizeLanguage = (language) =>
  supportedLanguages.includes(language) ? language : 'en';

const getSavedLanguage = () => {
  try {
    return normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));
  } catch (error) {
    return 'en';
  }
};

export const translateText = (text, language = 'en') => {
  const normalizedLanguage = normalizeLanguage(language);
  if (normalizedLanguage === 'en' || typeof text !== 'string') {
    return text;
  }

  const dictionaries = {
    am: amharicTranslations,
    om: afaanOromoTranslations,
    ti: tigrinyaTranslations,
    sid: sidamaTranslations,
  };
  const dictionary = dictionaries[normalizedLanguage];
  if (Object.prototype.hasOwnProperty.call(dictionary, text)) {
    return dictionary[text];
  }

  const leadingWhitespace = text.match(/^\s*/)?.[0] || '';
  const trailingWhitespace = text.match(/\s*$/)?.[0] || '';
  const trimmedText = text.trim();
  const unreadNotifications = trimmedText.match(/^Notifications,\s*(\d+)\s*unread$/i);
  if (unreadNotifications) {
    const unreadTranslations = {
      am: `ማሳወቂያዎች፣ ${unreadNotifications[1]} ያልተነበቡ`,
      om: `Beeksisawwan, ${unreadNotifications[1]} hin dubbifamne`,
      ti: `ምልክታታት፣ ${unreadNotifications[1]} ዘይተነበቡ`,
      sid: `Beeshsha, ${unreadNotifications[1]} nabbantino`,
    };
    return `${leadingWhitespace}${unreadTranslations[normalizedLanguage]}${trailingWhitespace}`;
  }

  const currencyAmount = trimmedText.match(/^(?:Amount:\s*)?ETB\s+([\d,.]+)$/i);
  if (currencyAmount) {
    const hasAmountLabel = trimmedText.toLowerCase().startsWith('amount:');
    const currencyTranslations = {
      am: { label: 'መጠን፦ ', currency: 'ብር' },
      om: { label: 'Hamma: ', currency: 'Birrii' },
      ti: { label: 'መጠን፦ ', currency: 'ብር' },
      sid: { label: 'Hala: ', currency: 'Birrii' },
    };
    const translation = currencyTranslations[normalizedLanguage];
    return `${leadingWhitespace}${hasAmountLabel ? translation.label : ''}${translation.currency} ${currencyAmount[1]}${trailingWhitespace}`;
  }

  const translation = dictionary[trimmedText];

  return translation
    ? `${leadingWhitespace}${translation}${trailingWhitespace}`
    : text;
};

const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(getSavedLanguage);
  const textRecords = useRef(new WeakMap());
  const attributeRecords = useRef(new WeakMap());

  const setLanguage = useCallback((nextLanguage) => {
    const next = normalizeLanguage(nextLanguage);
    setLanguageState(next);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch (error) {
      // Keep the in-memory preference when storage is unavailable.
    }
  }, []);

  const t = useCallback(
    (text, values = {}) => {
      const translated = translateText(text, language);
      return translated.replace(/\{\{?(\w+)\}?\}/g, (match, key) =>
        Object.prototype.hasOwnProperty.call(values, key)
          ? String(values[key])
          : match
      );
    },
    [language]
  );

  const formatDate = useCallback(
    (date, options) =>
      new Intl.DateTimeFormat(
        { am: 'am-ET', om: 'om-ET', ti: 'ti-ET', sid: 'sid-ET', en: 'en-ET' }[language],
        options
      ).format(
        date instanceof Date ? date : new Date(date)
      ),
    [language]
  );

  const formatCurrency = useCallback(
    (amount, currency = 'ETB') =>
      new Intl.NumberFormat({ am: 'am-ET', om: 'om-ET', ti: 'ti-ET', sid: 'sid-ET', en: 'en-ET' }[language], {
        style: 'currency',
        currency,
        maximumFractionDigits: 2,
      }).format(Number(amount)),
    [language]
  );

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    const root = document.getElementById('root') || document.body;

    const translatableAttributes = ['aria-label', 'placeholder', 'title', 'alt'];

    const localizeTextNode = (node) => {
      const previous = textRecords.current.get(node);
      if (previous && node.data === previous.rendered) {
        const rendered = translateText(previous.source, language);
        if (node.data !== rendered) node.data = rendered;
        textRecords.current.set(node, { source: previous.source, rendered });
        return;
      }

      const source = node.data;
      const rendered = translateText(source, language);
      textRecords.current.set(node, { source, rendered });
      if (node.data !== rendered) node.data = rendered;
    };

    const localizeAttribute = (element, name) => {
      const records = attributeRecords.current.get(element) || {};
      const previous = records[name];
      const current = element.getAttribute(name);
      if (current === null) return;

      const source = previous && current === previous.rendered
        ? previous.source
        : current;
      const rendered = translateText(source, language);
      records[name] = { source, rendered };
      attributeRecords.current.set(element, records);
      if (current !== rendered) element.setAttribute(name, rendered);
    };

    const localizeNode = (node) => {
      if (node.nodeType === Node.TEXT_NODE) {
        localizeTextNode(node);
        return;
      }

      if (node.nodeType !== Node.ELEMENT_NODE) return;
      translatableAttributes.forEach((name) => localizeAttribute(node, name));
      node.childNodes.forEach(localizeNode);
    };

    localizeNode(root);
    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === 'characterData') {
          localizeTextNode(mutation.target);
        } else if (mutation.type === 'attributes') {
          localizeAttribute(mutation.target, mutation.attributeName);
        } else {
          mutation.addedNodes.forEach(localizeNode);
        }
      });
    });

    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: translatableAttributes,
    });

    return () => observer.disconnect();
  }, [language]);

  const value = useMemo(
    () => ({ language, setLanguage, t, formatDate, formatCurrency }),
    [language, setLanguage, t, formatDate, formatCurrency]
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

export const useTranslation = useLanguage;
